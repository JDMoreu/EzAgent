/// Something that prevents a member from working (see `incidents.py`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Incident {
    /// Incident number.
    pub id: i64,
    /// Swarm id.
    pub swarm: String,
    /// Affected member.
    pub member: String,
    /// Cause classification.
    pub kind: String,
    /// One-line detail.
    pub detail: String,
    /// Reset time offered to the user.
    pub resets: f64,
    /// `open`, `waiting` or `resolved`.
    pub state: String,
    /// Action taken when it was resolved.
    pub action: String,
    /// Creation timestamp.
    pub created: f64,
    /// Last update timestamp.
    pub updated: f64,
}

/// `" ".join(str(value or "").replace("\x00", " ").split())`.
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn task_line_matches_python_format() {
        let task = Task {
            id: 3,
            title: "Lexer".to_string(),
            role: "dev".to_string(),
            owner: String::new(),
            state: "pending".to_string(),
            deps: vec![1, 2],
            parent: 0,
            result: String::new(),
            rounds: 0,
            updated: 0.0,
        };
        assert_eq!(task.line(""), "T3 · Lexer [dev] tras T1,T2");
        let done = Task {
            owner: "bo".to_string(),
            state: "done".to_string(),
            result: "ok".to_string(),
            ..task
        };
        assert_eq!(done.line("2/3"), "T3 ✓ Lexer @bo 2/3 → ok");
    }

    #[test]
    fn message_line_and_member_label() {
        let message = Message {
            id: 7,
            sender: "ana".to_string(),
            recipient: BROADCAST.to_string(),
            kind: "info".to_string(),
            body: "hola".to_string(),
            ref_: "a.md".to_string(),
            ts: 0.0,
        };
        assert_eq!(message.line(), "#7 ana→todos info: hola [a.md]");
        let member = Member {
            name: "ana".to_string(),
            role: "plan".to_string(),
            agent: "claude".to_string(),
            address: String::new(),
            state: "working".to_string(),
            seen: 0.0,
            model: String::new(),
            effort: String::new(),
        };
        assert_eq!(member.label(), "ana(claude) trabaja");
    }
}
