/// A member of the swarm.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Member {
    /// Normalized name.
    pub name: String,
    /// Normalized role (empty means any).
    pub role: String,
    /// Agent CLI that runs the member.
    pub agent: String,
    /// Address of the member's terminal.
    pub address: String,
    /// One of [`MEMBER_STATES`].
    pub state: String,
    /// Last time the member was seen.
    pub seen: f64,
    /// Model chosen for the member.
    pub model: String,
    /// Effort chosen for the member.
    pub effort: String,
}

impl Member {
    /// `Member.label`: name, optional agent and state in Spanish.
    pub fn label(&self) -> String {
        let agent = if self.agent.is_empty() {
            String::new()
        } else {
            format!("({})", self.agent)
        };
        format!("{}{agent} {}", self.name, member_state(&self.state))
    }
}

/// A task of the board.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Task {
    /// Task number.
    pub id: i64,
    /// One-line title.
    pub title: String,
    /// Role that may take it (empty means any).
    pub role: String,
    /// Member that owns it.
    pub owner: String,
    /// `pending`, `claimed`, `done` or `failed`.
    pub state: String,
    /// Tasks that must finish first.
    pub deps: Vec<i64>,
    /// Parent task, 0 when it is not a part.
    pub parent: i64,
    /// One-line result.
    pub result: String,
    /// Reopen rounds used.
    pub rounds: i64,
    /// Last update timestamp.
    pub updated: f64,
}

impl Task {
    /// One board line; `parts` is «hechas/total» when the task has parts.
    pub fn line(&self, parts: &str) -> String {
        let who = if !self.owner.is_empty() {
            format!(" @{}", self.owner)
        } else if !self.role.is_empty() {
            format!(" [{}]", self.role)
        } else {
            String::new()
        };
        let deps = if !self.deps.is_empty() && self.state == "pending" {
            let names: Vec<String> = self.deps.iter().map(|dep| format!("T{dep}")).collect();
            format!(" tras {}", names.join(","))
        } else {
            String::new()
        };
        let progress = if parts.is_empty() {
            String::new()
        } else {
            format!(" {parts}")
        };
        let result = if self.result.is_empty() {
            String::new()
        } else {
            format!(" → {}", self.result)
        };
        let mark = task_mark(&self.state);
        format!(
            "T{} {mark} {}{who}{progress}{deps}{result}",
            self.id, self.title
        )
    }
}

/// A board message.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Message {
    /// Message number.
    pub id: i64,
    /// Member that sent it.
    pub sender: String,
    /// Member or [`BROADCAST`].
    pub recipient: String,
    /// One of [`MESSAGE_KINDS`].
    pub kind: String,
    /// One-line body.
    pub body: String,
    /// Optional reference path.
    #[serde(rename = "ref")]
    pub ref_: String,
    /// Creation timestamp.
    pub ts: f64,
}

impl Message {
    /// One board line.
    pub fn line(&self) -> String {
        let target = if self.recipient == BROADCAST {
            "todos"
        } else {
            &self.recipient
        };
        let reference = if self.ref_.is_empty() {
            String::new()
        } else {
            format!(" [{}]", self.ref_)
        };
        format!(
            "#{} {}→{target} {}: {}{reference}",
            self.id, self.sender, self.kind, self.body
        )
    }
}

/// A file reservation.
