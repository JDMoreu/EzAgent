/// Accepted message kinds (`MESSAGE_KINDS`).
pub const MESSAGE_KINDS: [&str; 7] = ["info", "ask", "answer", "done", "block", "fix", "sys"];

/// Member state and its Spanish label (`MEMBER_STATES`).
pub const MEMBER_STATES: [(&str, &str); 4] = [
    ("idle", "libre"),
    ("working", "trabaja"),
    ("blocked", "bloqueado"),
    ("gone", "fuera"),
];

/// Swarm state and its Spanish label (`SWARM_STATES`).
pub const SWARM_STATES: [(&str, &str); 5] = [
    ("setup", "preparando"),
    ("active", "activo"),
    ("paused", "en pausa"),
    ("done", "terminado"),
    ("stopped", "detenido"),
];

/// Mark shown before a task title (`TASK_MARKS`).
pub const TASK_MARKS: [(&str, &str); 4] = [
    ("pending", "·"),
    ("claimed", "▶"),
    ("done", "✓"),
    ("failed", "✗"),
];

/// `MEMBER_STATES.get(state, state)`.
pub fn member_state(state: &str) -> &str {
    table_get(&MEMBER_STATES, state).unwrap_or(state)
}

/// `SWARM_STATES.get(state, state)`.
pub fn swarm_state(state: &str) -> &str {
    table_get(&SWARM_STATES, state).unwrap_or(state)
}

/// `TASK_MARKS.get(state, "?")`.
pub fn task_mark(state: &str) -> &str {
    table_get(&TASK_MARKS, state).unwrap_or("?")
}

fn table_get<'a>(table: &'a [(&'a str, &'a str)], key: &str) -> Option<&'a str> {
    table
        .iter()
        .find(|(name, _)| *name == key)
        .map(|(_, value)| *value)
}

/// Invalid board request; its message is readable by the agent.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SwarmError {
    message: String,
}

impl SwarmError {
    /// Builds the error with the exact text the Python code raises.
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }

    /// Message shown to the agent.
    pub fn message(&self) -> &str {
        &self.message
    }
}

impl fmt::Display for SwarmError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl std::error::Error for SwarmError {}

