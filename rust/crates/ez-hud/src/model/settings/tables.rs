pub const VOICE_LABELS: [(&str, &str); 3] = [
    ("em_alex", "Álex · masculina"),
    ("ef_dora", "Dora · femenina"),
    ("em_santa", "Santa · masculina grave"),
];

pub const VOICE_IDS: [&str; 3] = ["em_alex", "ef_dora", "em_santa"];

/// `VOICE_LABELS.get(ident, ident)`.
pub fn voice_label(ident: &str) -> Option<&'static str> {
    VOICE_LABELS
        .iter()
        .find(|(id, _)| *id == ident)
        .map(|(_, label)| *label)
}

